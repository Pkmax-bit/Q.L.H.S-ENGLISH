export function getUnitStudy(unitNo, kind) {
  const bank = TCO_STUDY_BANK[Number(unitNo)] || null
  if (!bank) return null
  const lesson = kind && bank.byKind?.[kind]
  if (!lesson) return bank
  return {
    vocab: lesson.vocab || bank.vocab,
    questions: lesson.questions || bank.questions,
    speak: lesson.speak || bank.speak,
    write: lesson.write || bank.write,
    byKind: bank.byKind,
  }
}

