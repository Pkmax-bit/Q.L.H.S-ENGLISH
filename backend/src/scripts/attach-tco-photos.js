/**
 * Copy real TCO course photos (not homemade SVGs) into uploads/tco/photos
 * and write frontend/src/data/tcoCoursePhotos.js
 *
 * Usage (from backend/):
 *   node src/scripts/attach-tco-photos.js
 */
require('dotenv').config({ path: require('path').join(__dirname, '../../.env') })
const fs = require('fs')
const path = require('path')

const DEFAULT_SRC = path.join(
  process.env.USERPROFILE || process.env.HOME || '',
  'Downloads',
  'TOEIC-Compact-550+',
  'TOEIC-Compact-550+'
)
const SRC = process.env.TCO_MEDIA_DIR || DEFAULT_SRC
const DEST = path.join(__dirname, '../../uploads/tco/photos')
const MAP_FILE = path.join(__dirname, '../../../frontend/src/data/tcoCoursePhotos.js')
const AVATAR_SIZE = 89928
const MIN_SIZE = 28000

function walk(dir, acc = []) {
  if (!fs.existsSync(dir)) return acc
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) walk(full, acc)
    else acc.push(full)
  }
  return acc
}

function isCoursePhoto(file) {
  const ext = path.extname(file).toLowerCase()
  if (!['.jpg', '.jpeg', '.png', '.webp'].includes(ext)) return false
  const rel = file.replace(/\\/g, '/')
  if (rel.includes('/screenshots/')) return false
  const size = fs.statSync(file).size
  if (size === AVATAR_SIZE) return false
  if (size < MIN_SIZE) return false
  return true
}

function uniqueBySize(files) {
  const seen = new Set()
  const out = []
  files.sort((a, b) => a.localeCompare(b, 'en'))
  for (const file of files) {
    const size = fs.statSync(file).size
    if (seen.has(size)) continue
    seen.add(size)
    out.push(file)
  }
  return out
}

function lessonKindFromPath(rel) {
  const norm = rel.replace(/\\/g, '/')
  if (norm.includes('/extension/')) return 'extension'
  if (norm.includes('/mini-test/')) return 'mini-test'
  const match = norm.match(/\/lesson-(\d+)\//)
  if (match) return `lesson-${match[1]}`
  return 'other'
}

function preferPractice(files) {
  const practice = files.filter((file) => /\/practice-\d+\//i.test(file.replace(/\\/g, '/')))
  const extra = files.filter((file) => !/\/practice-\d+\//i.test(file.replace(/\\/g, '/')))
  return [...practice, ...extra]
}

function copyFile(src, dest) {
  fs.mkdirSync(path.dirname(dest), { recursive: true })
  if (fs.existsSync(dest) && fs.statSync(dest).size === fs.statSync(src).size) return false
  fs.copyFileSync(src, dest)
  return true
}

function main() {
  if (!fs.existsSync(SRC)) {
    console.error(`Không thấy thư mục media: ${SRC}`)
    process.exit(1)
  }

  fs.mkdirSync(DEST, { recursive: true })
  const map = {}
  let copied = 0

  for (let unit = 1; unit <= 29; unit += 1) {
    const unitDir = path.join(SRC, `unit-${unit}`)
    if (!fs.existsSync(unitDir)) continue
    const grouped = {}
    uniqueBySize(walk(unitDir).filter(isCoursePhoto)).forEach((file) => {
      const kind = lessonKindFromPath(file.slice(unitDir.length))
      if (!grouped[kind]) grouped[kind] = []
      grouped[kind].push(file)
    })

    Object.entries(grouped).forEach(([kind, files]) => {
      const ordered = preferPractice(files)
      const urls = []
      ordered.forEach((src, idx) => {
        const ext = path.extname(src).toLowerCase()
        const destName = `u${String(unit).padStart(2, '0')}-${kind}-${idx + 1}${ext}`
        const dest = path.join(DEST, destName)
        if (copyFile(src, dest)) copied += 1
        urls.push(`/uploads/tco/photos/${destName}`)
      })
      if (!map[unit]) map[unit] = {}
      map[unit][kind] = urls
    })
  }

  const js = `/* Generated by backend/src/scripts/attach-tco-photos.js — do not edit by hand. */\n`
    + `export const TCO_COURSE_PHOTOS = ${JSON.stringify(map, null, 2)}\n\n`
    + `export function coursePhotoKindFromTitle(title) {\n`
    + `  const text = String(title || '')\n`
    + `  if (/Extension\\b/i.test(text)) return 'extension'\n`
    + `  if (/Mini\\s*Test\\b/i.test(text)) return 'mini-test'\n`
    + `  const lesson = text.match(/Lesson\\s+(\\d+)/i)\n`
    + `  if (lesson) return 'lesson-' + lesson[1]\n`
    + `  if (/TOEIC có thật sự khó/i.test(text)) return 'lesson-1'\n`
    + `  if (/Tìm hiểu TOEIC/i.test(text)) return 'lesson-2'\n`
    + `  if (/Hướng dẫn học tập/i.test(text)) return 'lesson-3'\n`
    + `  const kind = text.match(/Bài\\s+(\\d+)/i)\n`
    + `  if (kind) return 'lesson-' + kind[1]\n`
    + `  return 'lesson-1'\n`
    + `}\n\n`
    + `export function getCoursePhotos(unit, kind) {\n`
    + `  const unitMap = TCO_COURSE_PHOTOS[Number(unit)] || {}\n`
    + `  if (kind && unitMap[kind]?.length) return unitMap[kind]\n`
    + `  return []\n`
    + `}\n\n`
    + `export function getLessonCoursePhotos(lesson, limit = 4) {\n`
    + `  const title = lesson?.title || ''\n`
    + `  const unitMatch = String(title).match(/Unit\\s*0?(\\d+)/i)\n`
    + `  const unit = unitMatch ? Number(unitMatch[1]) : null\n`
    + `  if (!unit) return []\n`
    + `  const urls = getCoursePhotos(unit, coursePhotoKindFromTitle(title))\n`
    + `  return urls.slice(0, limit)\n`
    + `}\n`

  fs.mkdirSync(path.dirname(MAP_FILE), { recursive: true })
  fs.writeFileSync(MAP_FILE, js, 'utf8')

  const units = Object.keys(map).length
  const photos = Object.values(map).reduce((sum, kinds) => (
    sum + Object.values(kinds).reduce((n, urls) => n + urls.length, 0)
  ), 0)
  console.log(`Đã copy ${copied} ảnh mới, tổng ${photos} ảnh / ${units} unit`)
  console.log(`Map: ${MAP_FILE}`)
  console.log(`Files: ${DEST}`)
}

main()
